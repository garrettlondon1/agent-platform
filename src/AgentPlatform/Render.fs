/// How each kind of hook carries the platform token (when `hookTokenFrom` is set):
///   exec curl.exe  curl's own `--variable %NAME --expand-header` reads the environment (no shell needed)
///   bash curl      "$NAME" in the command
///   http hook      `allowedEnvVars` + ${NAME} in the header value (hooks-reference "HTTP hooks")
let private curlAuthArgs (p: Platform) =
    (match p.HostCaPath with
     // Schannel cannot check revocation for a private CA, so it is skipped for that CA only.
     | Some pem -> [ "--cacert"; pem; "--ssl-no-revoke" ]
     | None -> [])
    @ (match p.HookTokenVariable with
       | Some v -> [ "--variable"; $"%%{v}"; "--expand-header"; "Authorization: Bearer {{" + v + "}}" ]
       | None -> [])

let private bashAuth (p: Platform) =
    match p.HookTokenVariable with
    | Some v -> $" -H \"Authorization: Bearer ${{{v}}}\""
    | None -> ""

/// The deciding hook, with nothing installed and no shell start-up.
///   machine / plugin layers  `exec curl.exe` - runs the executable directly, no shell at all
///                            (`exec` is CLI-only and cannot be combined with bash/powershell)
///   repository layer         `bash` curl - the only field cloud agent honours, also fine on Linux/macOS
/// `--fail` makes an unreachable or erroring service a non-zero exit, and a non-zero preToolUse
/// command hook DENIES (hooks-reference "Exit codes for command hooks": fail-closed).
let private decidingCommand (p: Platform) (event: HookEvent) (source: string) (forRepository: bool) =
    let url = $"{hooksUrl p}?decide=1"
    if forRepository then
        let bash =
            $"curl -sS --fail --max-time 4{bashAuth p} -H 'Content-Type: application/json' -H 'X-Agentp-Event: {event.Name}' -H 'X-Agentp-Source: {source}' --data-binary @- '{url}' || exit 2"
        obj [ "type", Some(str "command"); "bash", Some(str bash); "timeoutSec", Some(num 5) ]
    else
        obj [
            "type", Some(str "command")
            "exec", Some(str "curl.exe")
            "args",
            Some(
                strs (
                    [ "-sS"; "--fail"; "--max-time"; "4" ]
                    @ curlAuthArgs p
                    @ [
                        "-H"; "Content-Type: application/json"
                        "-H"; $"X-Agentp-Event: {event.Name}"
                        "-H"; $"X-Agentp-Source: {source}"
                        "--data-binary"; "@-"
                        url
                    ]
                )
            )
            "timeoutSec", Some(num 5)
        ]

/// Capture: an HTTP hook. The runtime POSTs the payload itself - no process starts at all.
let private httpHook (p: Platform) (event: HookEvent) (source: string) =
    let auth, allowed =
        match p.HookTokenVariable with
        | Some v -> [ "Authorization", str ("Bearer ${" + v + "}") ], Some(strs [ v ])
        | None -> [], None
    obj [
        "type", Some(str "http")
        "url", Some(str (hooksUrl p))
        "headers", Some(objOf ([ "X-Agentp-Event", str event.Name; "X-Agentp-Source", str source ] @ auth))
        "allowedEnvVars", allowed
        "timeoutSec", Some(num 5)
    ]

/// A trailing transfer that cannot fail on Windows, so the exit code reports it rather than the collector call.
let private alwaysSucceeds = [ "--next"; "-s"; "-o"; "NUL"; "file:///C:/Windows/win.ini" ]

/// Capture over curl, for hosts on internal networks. Fail-OPEN: no `|| exit 2`, and non-deciding
/// events ignore non-zero exits, so a collector outage never blocks anyone.
let private curlCapture (p: Platform) (event: HookEvent) (source: string) (forRepository: bool) =
    let url = hooksUrl p
    if forRepository then
        let bash =
            $"curl -sS --max-time 4{bashAuth p} -H 'Content-Type: application/json' -H 'X-Agentp-Event: {event.Name}' -H 'X-Agentp-Source: {source}' --data-binary @- '{url}' >/dev/null || true"
        obj [ "type", Some(str "command"); "bash", Some(str bash); "timeoutSec", Some(num 5) ]
    else
        obj [
            "type", Some(str "command")
            "exec", Some(str "curl.exe")
            // curl exits with the LAST transfer's result. A non-zero preToolUse command hook DENIES (hooks-reference
            // "Exit codes for command hooks"), so a capture-only hook ends with a local file read that always succeeds:
            // an unreachable collector can never block a tool call. Deciding hooks (decidingCommand) keep --fail.
            "args", Some(strs ([ "-sS"; "--max-time"; "4"; "-o"; "NUL" ] @ curlAuthArgs p @ [ "-H"; "Content-Type: application/json"; "-H"; $"X-Agentp-Event: {event.Name}"; "-H"; $"X-Agentp-Source: {source}"; "--data-binary"; "@-"; url ] @ alwaysSucceeds))
            "timeoutSec", Some(num 5)
        ]

/// A hooks.json for one layer. Events a rule can decide go through a fail-closed command;
/// everything else is captured the way the platform's hooks { } chose (HTTP hooks by default).
let hooksJson (p: Platform) (source: string) (forCloudAgent: bool) =
    let h = p.Hooks
    let deciding = decidingEvents h |> Set.ofList
    let events =
        eventsFor h
        |> List.filter (fun e -> not forCloudAgent || e.FiresInCloudAgent)
    let entries =
        events
        |> List.map (fun e ->
            let entry =
                if deciding.Contains e then decidingCommand p e source forCloudAgent
                else
                    match h.CaptureVia with
                    | HttpHooks -> httpHook p e source
                    | CurlCommands -> curlCapture p e source forCloudAgent
            match matcherFor h e with
            | Some m when deciding.Contains e -> (entry :?> JsonObject)["matcher"] <- str m
            | _ -> ()
            e.Name, arr [ entry ])
    objOf [ "version", num 1; "hooks", objOf entries ]

/// The rule set itself, as data, so the daemon can load it without the F# definition.
let rulesJson (p: Platform) =
    let rec cond (c: Condition) : JsonNode =
        match c with
        | ToolIs names -> objOf [ "toolIs", strs names ]
        | ArgsMatch r -> objOf [ "argsMatch", str r ]
        | CommandStartsWith s -> objOf [ "commandStartsWith", str s ]
        | PathMatches g -> objOf [ "pathMatches", str g ]
        | PromptContains s -> objOf [ "promptContains", str s ]
        | OnSurface ss -> objOf [ "onSurface", strs (ss |> List.map _.Text) ]
        | All cs -> objOf [ "all", (cs |> List.map cond |> arr) ]
        | AnyOf cs -> objOf [ "anyOf", (cs |> List.map cond |> arr) ]
        | Not c -> objOf [ "not", cond c ]
        | Always -> objOf [ "always", bool true ]
    let rec action =
        function
        | DryRun a -> objOf [ "dryRun", action a ]
        | Block r -> objOf [ "block", str r ]
        | RequireApproval r -> objOf [ "requireApproval", str r ]
        | Approve -> objOf [ "approve", bool true ]
        | AddContext t -> objOf [ "addContext", str t ]
        | KeepGoing t -> objOf [ "keepGoing", str t ]
        | Record -> objOf [ "record", bool true ]
    objOf [
        "version", str p.Version
        "rules",
        p.Hooks.Rules
        |> List.map (fun r ->
            obj [
                "name", Some(str r.Name)
                "description", (if r.Description = "" then None else Some(str r.Description))
                "events", Some(strs (r.Events |> List.map _.Name))
                "when", Some(cond r.When)
                "then", Some(action r.Then)
                "onFailure", Some(str (match r.OnFailure with FailClosed -> "closed" | FailOpen -> "open"))
            ])
        |> arr
        "capture",
        match p.Hooks.Capture with
        | Some c -> objOf [ "events", strs (c.Events |> List.map _.Name); "includeContent", bool c.IncludeContent ]
        | None -> objOf [ "events", strs [] ]
    ]

