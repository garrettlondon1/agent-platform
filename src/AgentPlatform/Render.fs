/// Rendering a platform { } into every file GitHub, the clients and gh-aw read.
///
/// Output is a tree of repositories, each committed and pushed as-is by the deploy workflow:
///
///     .github-private/            enterprise "Configuration source": managed settings, teams, agents
///     copilot-plugins/            the marketplace: plugins carrying skills, agents, standards, MCP, hooks
///     repo-baseline/              synced into every repository: instructions, AGENTS.md, .github/hooks
///     agentic-workflows/          gh-aw workflows, shared governance import, gh aw env defaults
///     endpoints/                  the platform host's static content: v0.1 MCP registry
///     workstation/                file-based + MDM managed settings and machine-wide policy hooks
///     github/                     REST bodies for rulesets, content exclusion, cloud agent (applied by `agentp apply`)
///     platform.lock.json          version + content hash of everything above
