let githubApi (p: Platform) = [
    for r in p.GitHub.Rulesets do
        file $"github/rulesets/{r.Name}.json" (render (rulesetJson r))
    if not p.GitHub.ContentExclusion.IsEmpty then
        file "github/copilot-content-exclusion.json" (render (contentExclusionJson p.GitHub))
    file "github/cloud-agent-permissions.json" (render (cloudAgentPermissionsJson p.GitHub))
    let cloudMcp = p.Mcp.Servers |> List.filter (fun s -> p.Agents |> List.exists (fun a -> List.contains s.Key a.Mcp))
    // GET-only API: this is the configuration every repository is expected to have; `plan` compares against it.
    file "github/cloud-agent-expected-configuration.json" (render (cloudAgentConfigJson p.GitHub (Some(cloudAgentConfig cloudMcp))))
    file "github/agents-variables.json" (p.GitHub.AgentVariables |> List.map (fun (k, v) -> k, str v) |> objOf |> render)
    file "github/organization-custom-instructions.md" (organizationInstructions p.Standards + "\n")
    file "github/mcp-policy.json" (
        obj [
            "mcp_servers_in_copilot", Some(str "enabled")
            "mcp_registry_url", p.Mcp.RegistryUrl |> Option.orElse (Some $"{p.Host}") |> Option.map str
            "restrict_mcp_access_to_registry", Some(str (match p.Mcp.RegistryMode with RegistryOnly -> "registry_only" | DiscoveryOnly -> "allow_all"))
        ]
        |> render)
]

