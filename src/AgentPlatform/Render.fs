let all (p: Platform) (published: DateTimeOffset) =
    let p = staged p
    let files =
        githubPrivate p @ marketplaceFiles p @ repoBaseline p @ agenticWorkflows p @ endpoints p published @ workstation p @ githubApi p
        @ [ file "coverage.json" (render (coverage p)) ]
    let hash (s: string) = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes s)).ToLowerInvariant()
    let lock =
        objOf [
            "platform", str p.Name
            "organization", str p.Organization
            "version", str p.Version
            "rollout", str (string p.Rollout)
            "files", (files |> List.sortBy _.Path |> List.map (fun f -> f.Path, str (hash f.Content)) |> objOf)
        ]
    files @ [ file "platform.lock.json" (render lock) ]

let writeTo (outDir: string) (files: File list) =
    for f in files do
        let path = Path.Combine(outDir, f.Path)
        Directory.CreateDirectory(Path.GetDirectoryName path) |> ignore
        let content = f.Content.Replace("\r\n", "\n")
        let content = if f.Path.EndsWith ".ps1" || f.Path.EndsWith ".reg" then content.Replace("\n", "\r\n") else content
        File.WriteAllText(path, content, UTF8Encoding(false))
    files.Length
