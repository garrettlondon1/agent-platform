let private yamlList (xs: string list) = "[" + (xs |> List.map yamlString |> String.concat ", ") + "]"

/// gh-aw's built-in tool names (pkg/workflow/mcp_config_validation.go builtInToolNames).
/// Tracked by Drift ("gh-aw.builtin-tools") so a new reserved name is caught automatically.
let ghAwReservedToolNames = [
    "github"; "jira"; "playwright"; "agentic-workflows"; "cache-memory"; "drive-memory"; "comment-memory"; "repo-memory"
    "ledger"; "work-queue"; "bash"; "edit"; "web-fetch"; "web-search"; "linear"; "safety-prompt"; "timeout"; "startup-timeout"; "cli-proxy"
]

let workflowMarkdown (p: Platform) (w: Workflow) =
    let a = agentNamed p w.Agent |> Option.get
    let host = Uri(p.Host).Host
    let sb = StringBuilder()
    let line (s: string) = sb.Append(s).Append('\n') |> ignore
    line "---"
    line $"name: {yamlString w.Name}"
    line $"description: {yamlString w.Description}"
    line "on:"
    for t in w.On do
        match t with
        | Schedule s -> line $"  schedule: {yamlString s}"
        | PullRequestOpened -> line "  pull_request:"; line "    types: [opened, synchronize, reopened]"
        | IssueOpened -> line "  issues:"; line "    types: [opened]"
        | WorkflowFailed wfs -> line "  workflow_run:"; line $"    workflows: {yamlList wfs}"; line "    types: [completed]"; line "    branches: [main]"
        | Manually -> line "  workflow_dispatch:"
        | SlashCommand name -> line "  slash_command:"; line $"    name: {name}"
    if not (List.contains Manually w.On) then line "  workflow_dispatch:"
    line "permissions:"
    for r in w.Reads do line $"  {r}: read"
    line "  copilot-requests: write"
    line "engine:"
    line "  id: copilot"
    if w.CopilotSdk then line "  copilot-sdk: true"
    match a.Model with Some m -> line $"  model: {m}" | None -> ()
    line "strict: true"
    line $"timeout-minutes: {w.TimeoutMinutes}"
    match w.MaxAiCredits with Some c -> line $"max-ai-credits: {c}" | None -> ()
    line "network:"
    line "  allowed:"
    // An internal host is unreachable from GitHub-hosted runners (and gh-aw rejects it): leave it out.
    let platformHosts = if hostIsInternal p then [] else [ host ]
    for n in w.Network @ platformHosts |> List.distinct do line $"    - {yamlString n}"
    line "tools:"
    line "  github:"
    line $"    toolsets: {yamlList w.Toolsets}"
    if not w.Bash.IsEmpty then line $"  bash: {yamlList w.Bash}"
    if w.CanEdit then line "  edit:"
    let servers = serversNamed p a.Mcp |> List.filter (fun s -> match s.Transport with Remote _ -> true | _ -> (commandLine s).IsSome)
    if not servers.IsEmpty then
        line "mcp-servers:"
        for s in servers do
            // gh-aw reserves some names (github, jira, playwright, linear, ...) for first-class tools
            // with their own schema; custom servers must not collide with them.
            let key = if List.contains s.Key ghAwReservedToolNames then $"{p.Organization}-{s.Key}" else s.Key
            line $"  {key}:"
            match s.Transport, commandLine s with
            | Remote(url, _), _ ->
                line "    type: http"
                line $"    url: {yamlString url}"
                // gh-aw requires auth on remote servers: header secrets map to repository/org Actions secrets.
                let headers = s.Secrets |> List.filter _.Header
                if headers.IsEmpty then
                    line "    auth:"
                    line "      type: github-oidc"
                else
                    line "    headers:"
                    for h in headers do
                        let secret = "MCP_" + s.Key.ToUpperInvariant().Replace('-', '_') + "_" + h.Name.ToUpperInvariant().Replace('-', '_')
                        line $"      {h.Name}: \"${{{{ secrets.{secret} }}}}\""
            | _, Some(cmd, args) -> line "    type: stdio"; line $"    command: {yamlString cmd}"; line $"    args: {yamlList args}"
            | _ -> ()
            line $"    allowed: {yamlList s.Tools}"
    if not w.Plugins.IsEmpty then
        line "plugins:"
        for pl in w.Plugins do line $"  - {marketplaceRepo p}/plugins/{pl}@{p.MarketplaceRef}"
    line "safe-outputs:"
    for s in w.Writes do
        match s with
        | CreateIssue(prefix, labels, max) ->
            line "  create-issue:"; line $"    title-prefix: {yamlString prefix}"; line $"    labels: {yamlList labels}"; line $"    max: {max}"
        | AddComment max -> line "  add-comment:"; line $"    max: {max}"
        | AddLabels allowed -> line "  add-labels:"; line $"    allowed: {yamlList allowed}"
        | CreatePullRequest(prefix, draft) ->
            let draftText = if draft then "true" else "false"
            line "  create-pull-request:"; line $"    title-prefix: {yamlString prefix}"; line $"    draft: {draftText}"
        | ReviewPullRequest _ -> line "  submit-pull-request-review:"; line "    max: 1"; line "    allowed-events: [COMMENT, REQUEST_CHANGES]"
        | AssignToCopilot -> line "  assign-to-agent:"
        | Noop -> line "  noop:"
    line "imports:"
    line $"  - shared/{p.Organization}-governance.md"
    line $"  - .github/agents/{a.Name}.md"
    if not a.Evals.IsEmpty then
        line "evals:"
        for q in a.Evals do
            line $"  - id: {q.Id}"
            line $"    question: {yamlString q.Question}"
    match w.Graders with
    | [] -> ()
    | graders ->
        let custom = graders |> List.choose (function OperationalValue(n, d, u, s) -> Some(n, d, u, s) | _ -> None)
        if custom.IsEmpty then line "graders: {}"
        else
            line "graders:"
            for n, d, u, s in custom do
                line "  operational-value:"
                line $"    name: {yamlString n}"
                line $"    description: {yamlString d}"
                line $"    unit: {u}"
                line "    direction: higher_is_better"
                line "    script: |"
                for l in s.Trim().Split('\n') do line $"      {l.TrimEnd()}"
    if not w.Experiments.IsEmpty then
        line "experiments:"
        for x in w.Experiments do
            line $"  {x.Name}:"
            line $"    variants: {yamlList x.Variants}"
            line $"    metric: {yamlString x.Metric}"
            line $"    min_samples: {x.MinSamples}"
    line "---"
    line ""
    line $"# {w.Name}"
    line ""
    line (dedent w.Task)
    for x in w.Experiments do
        // gh-aw only authorises `{{#if experiments.<name> == '<variant>' }}` blocks in the prompt.
        for v in x.Variants do
            line ""
            line $"{{{{#if experiments.{x.Name} == '{v}' }}}}"
            line $"Work in a **{v}** way for this run."
            line "{{/if}}"
    sb.ToString()

let governanceImport (p: Platform) =
    let host = Uri(p.Host).Host
    let hostLine = if hostIsInternal p then "" else $"\n    - \"{host}\""
    $"""---
network:
  allowed:
    - "defaults"{hostLine}
---

<!--
{banner p}
Every {p.Name} agentic workflow imports this file. OTLP export is configured centrally (agentic-workflows/aw-defaults.yml
via `gh aw env update --scope org`), so no workflow can forget it; Copilot CLI inside the run exports to the same collector.
-->
"""

let agenticWorkflows (p: Platform) = [
    file $"agentic-workflows/.github/workflows/shared/{p.Organization}-governance.md" (governanceImport p)
    for w in p.Workflows do
        file $"agentic-workflows/.github/workflows/{w.Name}.md" (workflowMarkdown p w)
    for a in p.Agents |> List.filter (fun a -> p.Workflows |> List.exists (fun w -> w.Agent = a.Name)) do
        file $"agentic-workflows/.github/agents/{a.Name}.md" (profile p a)
    let defaults =
        p.AgenticDefaults @ (if hostIsInternal p then [] else [ "default_otlp_endpoint", p.Host ])
        |> List.distinctBy fst
        // `gh aw env` wants plain integers where frontmatter also accepts K/M suffixes ("2M").
        |> List.map (fun (k, v) ->
            let m = Text.RegularExpressions.Regex.Match(v.Trim(), "^(\d+)([KkMm])$")
            let v = if m.Success then string (int64 m.Groups[1].Value * (if m.Groups[2].Value.ToUpperInvariant() = "K" then 1000L else 1000000L)) else v
            k, v)
        |> List.map (fun (k, v) -> $"{k}: {yamlString v}")
        |> String.concat "\n"
    file "agentic-workflows/aw-defaults.yml" ($"# {banner p}\n" + defaults + "\n")
    file "agentic-workflows/aw-policy.json" (p.AgenticPolicy |> List.map (fun (k, v) -> k, str v) |> objOf |> render)
]

