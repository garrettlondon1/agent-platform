let marketplaceFiles (p: Platform) = [
    let m = marketplace p
    file "copilot-plugins/.github/plugin/marketplace.json" (render (marketplaceJson m))
    file "copilot-plugins/README.md" $"# {m.Name}\n\n{banner p}\n\nEvery plugin here is installed on every Copilot client by `enabledPlugins` in enterprise managed settings, and this is the only marketplace `strictKnownMarketplaces` allows.\n"
    for pl in m.Plugins do
        let root = $"copilot-plugins/plugins/{pl.Name}"
        let servers = serversNamed p pl.Mcp
        file $"{root}/plugin.json" (render (pluginJson pl (not servers.IsEmpty)))
        for s in pl.Skills do
            file $"{root}/skills/{s.Name}/SKILL.md" (skillMarkdown s)
            for path, content in s.Files do
                file $"{root}/skills/{s.Name}/{path}" content
        for s in standardsNamed p pl.Standards do
            let sk = standardAsSkill s
            file $"{root}/skills/{sk.Name}/SKILL.md" (skillMarkdown sk)
        for name in pl.Agents do
            match agentNamed p name with
            | Some a -> file $"{root}/agents/{a.Name}.agent.md" (profile p a)
            | None -> ()
        if not servers.IsEmpty then
            file $"{root}/.mcp.json" (render (pluginMcpJson servers))
        if pl.CarriesHooks then
            file $"{root}/hooks.json" (render (hooksJson p $"plugin:{pl.Name}" false))
            file $"{root}/hook-rules.json" (render (rulesJson p))
]

