let private yamlString (s: string) = "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\""

/// The `.agent.md` profile. One file serves every surface that reads custom agents.
let profile (p: Platform) (a: Agent) =
    let servers = serversNamed p a.Mcp
    let tools =
        a.Tools @ (a.Mcp |> List.map (fun m -> McpTools(m, "*")))
        |> List.distinct
        |> List.map (fun t -> yamlString t.Text)
        |> String.concat ", "
    let standards = standardsNamed p a.Standards
    let lines = [
        "---"
        $"name: {a.Name}"
        $"description: {yamlString a.Description}"
        if tools <> "" then $"tools: [{tools}]"
        match a.Model with Some m -> $"model: {m}" | None -> ()
        if a.OnlyWhenAsked then "disable-model-invocation: true"
        if a.NotUserSelectable then "user-invocable: false"
        yield! agentProfileYaml servers
        "metadata:"
        match a.Owner with Some o -> $"  owner: {yamlString o}" | None -> ()
        let governedBy = p.Organization + "/.github-private"
        $"  governed-by: {yamlString governedBy}"
        $"  platform-version: {yamlString p.Version}"
        if not a.Evals.IsEmpty then
            let ids = a.Evals |> List.map _.Id |> String.concat ","
            $"  evals: {yamlString ids}"
        "---"
        ""
        dedent a.Instructions
        for s in standards do
            ""
            $"## {s.Title}"
            ""
            yield! s.Rules |> List.map (fun r -> $"- {r}")
        if not a.Forbidden.IsEmpty then
            ""
            "Never read, search for, quote or summarise anything about: " + String.Join(", ", a.Forbidden) + "."
    ]
    String.concat "\n" lines + "\n"

